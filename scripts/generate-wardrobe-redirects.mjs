import fs from "node:fs/promises";
import path from "node:path";

// Exact CDN rewrites must run before Netlify serves the retained source PNGs.
const prefix = "/images/wardrobe/generated/onboarding/";
const catalog = JSON.parse(await fs.readFile("public/clothing-image-options.json", "utf8"));
if (!Array.isArray(catalog) || new Set(catalog).size !== catalog.length) {
  throw Error("Invalid wardrobe catalog");
}
const rules = [];
for (const file of catalog) {
  if (typeof file !== "string" || !/^[a-z0-9-]+\.png$/.test(file)) {
    throw Error("Invalid wardrobe default filename");
  }
  const target = file.replace(/\.png$/, ".webp");
  await fs.access(path.join("public", prefix, target));
  rules.push(`${prefix}${file} ${prefix}${target} 200!`);
}
await fs.writeFile("public/_redirects", "# Generated by scripts/generate-wardrobe-redirects.mjs. Put other rules in netlify.toml.\n" + rules.join("\n") + "\n");
console.log(`Prepared ${rules.length} wardrobe CDN rewrites.`);
